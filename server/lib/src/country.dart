/// Country codes for the national leaderboard (SPEC §4.6).
///
/// Why a national board at all: a global top 100 is unreachable for an ordinary
/// player, so it stops being a goal after the first look. A national one is
/// winnable, which is the whole point of showing a ranking.
///
/// The code is a **hint the client derives from the device locale**, never a
/// claim about where someone is. It is not verified against the submitter's
/// address (the stored `ip_hash` is a one-way digest, and geolocating it would
/// be both wrong and a privacy step backwards), so it is validated for shape
/// only: anything that is not a currently assigned ISO 3166-1 alpha-2 code is
/// dropped and the run is stored without one. A locale oddity must never cost
/// somebody a verified score.
library;

/// `GET /api/leaderboard` (or `/rank`) was asked for a country that is not an
/// ISO 3166-1 alpha-2 code (SPEC §4.6).
///
/// Deliberately *not* the same treatment a submission gets. Dropping an unusable
/// code on the way in costs nothing — the run is still stored and still ranked
/// globally — but dropping it on the way out would answer a request for one
/// country's board with the whole world's, which is a wrong answer rather than a
/// lenient one. This mirrors `invalid_period`, which the same endpoint has always
/// refused.
const String invalidCountryError = 'invalid_country';

/// Length of an ISO 3166-1 alpha-2 code.
const int countryCodeLength = 2;

