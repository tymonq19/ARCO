/// The uppercase ISO 3166-1 alpha-2 code [raw] denotes, or null when it is not
/// one (SPEC §4.6).
///
/// Surrounding whitespace and case are forgiven, because `pl` and ` PL ` are the
/// same hint. Nothing else is: a full locale tag (`pl_PL`, `en-GB`) is **not**
/// accepted, so a client that forwards the whole locale sees its runs stored
/// without a country and with no `country` key echoed back — which is the
/// cheapest possible way to notice the mistake. Sending the region subtag alone
/// is the contract.
String? normalizeCountryCode(Object? raw) {
  if (raw is! String) return null;
  final code = raw.trim().toUpperCase();
  if (code.length != countryCodeLength) return null;
  return isoCountryCodes.contains(code) ? code : null;
}
